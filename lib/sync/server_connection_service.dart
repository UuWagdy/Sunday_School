/// Holds the initial configuration loaded before `runApp()` so that
/// synchronous providers like `appDatabaseProvider` know immediately
/// whether to boot in Local SQLite mode or Server (.NET + PostgreSQL) mode.
class ServerBootstrap {
  static ServerConfig initialConfig = const ServerConfig();
  // Optional installation default; saved connection settings take precedence.
  static const String defaultServerUrl = String.fromEnvironment(
    'SYNC_DEFAULT_SERVER_URL',
  );

  static const String _prefIsServerMode = 'sync_is_server_mode';
  static const String _prefServerUrl = 'sync_server_url';
  static const String _prefDeviceId = 'sync_device_id';
  static const String _prefJwtToken = 'sync_jwt_token';

  static Future<void> ensureInitialized() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      var deviceId = prefs.getString(_prefDeviceId);
      if (deviceId == null || deviceId.trim().isEmpty) {
        final rand = Random().nextInt(900000) + 100000;
        final host = !kIsWeb ? Platform.localHostname : 'web';
        deviceId = '$host-$rand';
        await prefs.setString(_prefDeviceId, deviceId);
      }

      var serverUrl = prefs.getString(_prefServerUrl);
      if (serverUrl == null || serverUrl.trim().isEmpty) {
        serverUrl = defaultServerUrl.isNotEmpty
            ? defaultServerUrl
            : await discoverLocalServerUrl() ?? 'http://127.0.0.1:5050';
      }

      var isServerMode =
          prefs.getBool(_prefIsServerMode) ?? defaultServerUrl.isNotEmpty;
      var jwtToken = prefs.getString(_prefJwtToken);

      // Installing the server on a former client promotes it once. Later manual
      // connection choices still take precedence, and no database is replaced.
      if (!kIsWeb && Platform.isWindows) {
        final installRoot = File(Platform.resolvedExecutable).parent.path;
        final backend = File(
          p.join(
            installRoot,
            'Server',
            'backend',
            'SundaySchool.SyncServer.exe',
          ),
        );
        if (await backend.exists() &&
            prefs.getString('sync_host_installation') != installRoot) {
          serverUrl = 'http://127.0.0.1:5050';
          isServerMode = true;
          jwtToken = null;
          await prefs.setString('sync_host_installation', installRoot);
          await prefs.setString(_prefServerUrl, serverUrl);
          await prefs.setBool(_prefIsServerMode, true);
          await prefs.remove(_prefJwtToken);
        }
      }

      initialConfig = ServerConfig(
        isServerMode: isServerMode,
        serverUrl: serverUrl,
        deviceId: deviceId,
        jwtToken: jwtToken,
      );
    } catch (e) {
      debugPrint('ServerBootstrap.ensureInitialized error: $e');
    }
  }

  /// Reads `SERVER_INFO.txt` generated by `SundaySchoolServerManager` if present.
  static Future<String?> discoverLocalServerUrl() async {
    if (kIsWeb || !Platform.isWindows) return null;
    try {
      final candidates = <String>[
        r'C:\ProgramData\SundaySchool\SERVER_INFO.txt',
        p.join(
          File(Platform.resolvedExecutable).parent.path,
          'SERVER_INFO.txt',
        ),
        p.join(Directory.current.path, 'SERVER_INFO.txt'),
      ];
      for (final filePath in candidates) {
        final file = File(filePath);
        if (await file.exists()) {
          final lines = await file.readAsLines();
          for (final line in lines) {
            if (line.startsWith('LOCAL_URL=')) {
              final url = line.substring('LOCAL_URL='.length).trim();
              if (url.isNotEmpty) return url;
            }
          }
        }
      }
    } catch (_) {}
    return null;
  }

  /// Reads all URLs (`LOCAL_URL`, `LAN_URL`) from `SERVER_INFO.txt` if present.
  static Future<Map<String, String>> readServerInfoFile() async {
    final result = <String, String>{};
    if (kIsWeb || !Platform.isWindows) return result;
    try {
      final candidates = <String>[
        r'C:\ProgramData\SundaySchool\SERVER_INFO.txt',
        p.join(
          File(Platform.resolvedExecutable).parent.path,
          'SERVER_INFO.txt',
        ),
        p.join(Directory.current.path, 'SERVER_INFO.txt'),
      ];
      for (final filePath in candidates) {
        final file = File(filePath);
        if (await file.exists()) {
          final lines = await file.readAsLines();
          for (final line in lines) {
            final idx = line.indexOf('=');
            if (idx > 0) {
              final key = line.substring(0, idx).trim();
              final val = line.substring(idx + 1).trim();
              if (val.isNotEmpty) {
                result[key] = val;
              }
            }
          }
          if (result.isNotEmpty) break;
        }
      }
    } catch (_) {}
    return result;
  }
}

class ServerConfigNotifier extends Notifier<ServerConfig> {
  @override
  ServerConfig build() {
    return ServerBootstrap.initialConfig;
  }

  Future<void> updateSettings({
    required bool isServerMode,
    required String serverUrl,
  }) async {
    final normalized = ServerConfig(
      isServerMode: isServerMode,
      serverUrl: serverUrl.trim(),
      deviceId: state.deviceId,
      jwtToken: state.jwtToken,
    );
    final changed =
        state.isServerMode != isServerMode ||
        state.normalizedBaseUrl != normalized.normalizedBaseUrl;
    state = normalized.copyWith(
      serverUrl: normalized.normalizedBaseUrl,
      clearJwtToken: changed,
    );
    ServerBootstrap.initialConfig = state;

    final prefs = await SharedPreferences.getInstance();
    await prefs.setBool(ServerBootstrap._prefIsServerMode, state.isServerMode);
    await prefs.setString(ServerBootstrap._prefServerUrl, state.serverUrl);
    if (changed) await prefs.remove(ServerBootstrap._prefJwtToken);
  }

  Future<void> setJwtToken(String? token) async {
    state = state.copyWith(jwtToken: token, clearJwtToken: token == null);
    ServerBootstrap.initialConfig = state;

    final prefs = await SharedPreferences.getInstance();
    if (token == null) {
      await prefs.remove(ServerBootstrap._prefJwtToken);
    } else {
      await prefs.setString(ServerBootstrap._prefJwtToken, token);
    }
  }

  /// Tests connectivity and PostgreSQL status via `GET /health`.
  Future<ServerHealthResult> testConnection([String? customUrl]) async {
    final tempConfig = ServerConfig(serverUrl: customUrl ?? state.serverUrl);
    final url = '${tempConfig.normalizedBaseUrl}/health';
    final sw = Stopwatch()..start();

    try {
      final response = await http
          .get(Uri.parse(url), headers: {'Accept': 'application/json'})
          .timeout(const Duration(seconds: 5));
      sw.stop();

      if (response.statusCode == 200) {
        final data = jsonDecode(utf8.decode(response.bodyBytes));
        if (data is Map<String, dynamic>) {
          final service = (data['service'] ?? data['Service'] ?? '').toString();
          if (!service.startsWith('SundaySchool.SyncServer')) {
            return ServerHealthResult(
              ok: false,
              latencyMs: sw.elapsedMilliseconds,
              errorMessage:
                  'الرابط يخص برنامجًا آخر. استخدم سيرفر مدارس الأحد (المنفذ الافتراضي 5050).',
            );
          }
          final isDbConnected =
              (data['database'] ?? data['Database']) == 'connected';
          final isStatusOk = (data['status'] ?? data['Status']) == 'ok';
          final ok =
              data['ok'] == true ||
              data['Ok'] == true ||
              (isStatusOk && isDbConnected) ||
              isDbConnected;
          return ServerHealthResult(
            ok: ok,
            service:
                (data['service'] ??
                        data['Service'] ??
                        'SundaySchool.SyncServer')
                    .toString(),
            version: (data['version'] ?? data['Version'] ?? '1.0.0').toString(),
            database: (data['database'] ?? data['Database'] ?? 'connected')
                .toString(),
            engine: (data['engine'] ?? data['Engine'] ?? 'PostgreSQL')
                .toString(),
            latencyMs: sw.elapsedMilliseconds,
            errorMessage: ok
                ? null
                : (data['error'] ?? 'قاعدة البيانات غير متصلة').toString(),
          );
        }
      }

      return ServerHealthResult(
        ok: false,
        latencyMs: sw.elapsedMilliseconds,
        errorMessage:
            'استجابة غير متوقعة من السيرفر (HTTP ${response.statusCode})',
      );
    } catch (e) {
      sw.stop();
      return ServerHealthResult(
        ok: false,
        latencyMs: sw.elapsedMilliseconds,
        errorMessage: 'تعذر الاتصال بالسيرفر: $e',
      );
    }
  }

  /// Uploads the local SQLite database (`Betros_Bols.db`) to the .NET + PostgreSQL server.
  Future<Map<String, dynamic>> uploadLocalSqliteToServer({
    bool clearExisting = false,
  }) async {
    final dbFolder = await getAppDatabaseDirectory();
    final pointerFile = File(p.join(dbFolder.path, 'current_db.txt'));
    var dbName = 'Betros_Bols.db';
    if (await pointerFile.exists()) {
      final content = (await pointerFile.readAsString()).trim();
      if (content.isNotEmpty) dbName = content;
    }
    final dbFile = File(p.join(dbFolder.path, dbName));
    if (!await dbFile.exists()) {
      throw Exception('ملف قاعدة البيانات المحلية غير موجود: ${dbFile.path}');
    }

    final uri = Uri.parse(
      '${state.normalizedBaseUrl}/api/storage/import-sqlite?overwrite=$clearExisting&deviceId=${Uri.encodeQueryComponent(state.deviceId)}',
    );
    final request = http.MultipartRequest('POST', uri);
    request.headers['X-Device-Id'] = state.deviceId;
    if (state.jwtToken != null) {
      request.headers['Authorization'] = 'Bearer ${state.jwtToken}';
    }
    request.files.add(await http.MultipartFile.fromPath('file', dbFile.path));

    final streamed = await request.send().timeout(const Duration(minutes: 2));
    final response = await http.Response.fromStream(streamed);
    if (response.statusCode != 200) {
      throw Exception('فشل رفع قاعدة البيانات للسيرفر: ${response.body}');
    }
    final decoded = jsonDecode(utf8.decode(response.bodyBytes));
    return decoded is Map<String, dynamic> ? decoded : {'ok': true};
  }

  /// Downloads a full SQLite `.db` snapshot from the PostgreSQL database on the server.
  Future<Uint8List> downloadServerDatabaseAsSqliteBytes() async {
    final uri = Uri.parse(
      '${state.normalizedBaseUrl}/api/storage/export-sqlite',
    );
    final headers = <String, String>{'X-Device-Id': state.deviceId};
    if (state.jwtToken != null) {
      headers['Authorization'] = 'Bearer ${state.jwtToken}';
    }

    final response = await http
        .get(uri, headers: headers)
        .timeout(const Duration(minutes: 2));
    if (response.statusCode != 200) {
      throw Exception(
        'فشل تحميل النسخة الاحتياطية من السيرفر: ${response.body}',
      );
    }
    return response.bodyBytes;
  }
}

final serverConfigProvider =
    NotifierProvider<ServerConfigNotifier, ServerConfig>(
      ServerConfigNotifier.new,
    );
